# 2. Variables
name = "Uraish"
age = 20

print(name)
print(age)

# 3. Taking input
city = input("Enter your city: ")
print("You live in", city)

# 4. If-else
if age >= 18:
    print("You are an adult")
else:
    print("You are under 18")

# 5. Arithmetic
a = 10
b = 5

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)

# 6. For loop
for i in range(5):
    print(i)

# 7. While loop
count = 1

while count <= 5:
    print(count)
    count = count + 1

